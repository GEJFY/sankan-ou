async def seed_courses_and_topics(db: AsyncSession) -> dict[str, uuid.UUID]:
    """コースとトピックをシード"""
    course_ids: dict[str, uuid.UUID] = {}
    topic_map: dict[str, uuid.UUID] = {}  # "CIA::A. 内部監査の目的と権限" -> UUID

    for syllabus_file in sorted(SYLLABUS_DIR.glob("*.json")):
        with open(syllabus_file) as f:
            data = json.load(f)

        # コース作成
        existing = await db.execute(
            select(Course).where(Course.code == data["code"])
        )
        course = existing.scalar_one_or_none()
        # CIA/CISA/CFE は三冠対象のデフォルトコース
        default_courses = {"CIA", "CISA", "CFE"}

        if course is None:
            course = Course(
                code=data["code"],
                name=data["name"],
                color=data["color"],
                exam_config=data.get("exam_config"),
                is_default=data["code"] in default_courses,
            )
            db.add(course)
            await db.flush()
        elif course.is_default != (data["code"] in default_courses):
            course.is_default = data["code"] in default_courses
            await db.flush()

        course_ids[data["code"]] = course.id

        # トピック作成（既存トピックがあればスキップ）
        existing_topics = await db.execute(
            select(Topic).where(Topic.course_id == course.id).limit(1)
        )
        if existing_topics.scalar_one_or_none() is not None:
            # 既存トピックのマッピングを構築
            all_topics = await db.execute(
                select(Topic).where(Topic.course_id == course.id)
            )
            for t in all_topics.scalars().all():
                if t.level >= 1:
                    topic_map[f"{data['code']}::{t.name}"] = t.id
            continue

        sort_order = 0
        for part in data["topics"]:
            parent_topic = Topic(
                course_id=course.id,
                name=part["name"],
                weight_pct=part.get("weight_pct", 0),
                level=part.get("level", 0),
                sort_order=sort_order,
            )
            db.add(parent_topic)
            await db.flush()
            sort_order += 1

            for child in part.get("children", []):
                child_topic = Topic(
                    course_id=course.id,
                    parent_id=parent_topic.id,
                    name=child["name"],
                    weight_pct=child.get("weight_pct", 0),
                    level=child.get("level", 1),
                    sort_order=sort_order,
                )
                db.add(child_topic)
                await db.flush()
                topic_map[f"{data['code']}::{child['name']}"] = child_topic.id
                sort_order += 1

    return course_ids, topic_map


